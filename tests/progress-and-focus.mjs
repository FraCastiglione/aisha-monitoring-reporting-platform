import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const context=vm.createContext({window:{}});
vm.runInContext(read('assets/progress-guard.js'),context);
const guard=context.window.AISHA_PROGRESS.create();
let task='empty',comm='empty',partner='IF.E';
guard.register('IF.E:tasks',()=>partner==='IF.E'?task:null);
guard.register('IF.E:communication',()=>partner==='IF.E'?comm:null);
assert.equal(guard.hasUnsaved(),false);
task='first Task';assert.equal(guard.hasUnsaved(),true);
guard.protect('IF.E:tasks');assert.equal(guard.hasUnsaved(),false);
comm='communication';guard.protect('IF.E:tasks');assert.equal(guard.hasUnsaved(),true,'Saving Tasks cannot clear unsaved Communication');
const olderCopy={},newerCopy={};guard.rememberCopy(olderCopy,'IF.E:communication',comm);
comm='new communication';guard.rememberCopy(newerCopy,'IF.E:communication',comm);
guard.verifyCopy(olderCopy);assert.equal(guard.hasUnsaved(),true,'Verifying an older copy cannot clear newer edits');
guard.verifyCopy(newerCopy);assert.equal(guard.hasUnsaved(),false);
guard.invalidate('IF.E:tasks');assert.equal(guard.hasUnsaved(),true,'Deleting the browser backup restores protection');
partner='SC';assert.equal(guard.hasUnsaved(),false,'Other partner readers must be inactive');
partner='IF.E';guard.protect('IF.E:tasks');assert.equal(guard.hasUnsaved(),false);
console.log('Unsaved progress: independent reports, successful save, exact-copy identity, stale copies and deleted backups PASS');
let unloadHandler;
context.progressGuard=guard;
context.window.addEventListener=(type,listener)=>{if(type==='beforeunload')unloadHandler=listener;};
const unloadBinding=read('assets/reporting.js').split('\n').find(line=>line.includes("addEventListener('beforeunload'"));
vm.runInContext(unloadBinding,context);
let prevented=0;const leave={preventDefault(){prevented++;}};
unloadHandler(leave);assert.equal(prevented,0);
task='later edit';unloadHandler(leave);assert.equal(prevented,1);assert.equal(leave.returnValue,'');
guard.protect('IF.E:tasks');unloadHandler(leave);assert.equal(prevented,1,'A successfully saved report permits leaving');
console.log('Native beforeunload binding blocks dirty progress and allows protected progress PASS');

const controls=[];
const activeTab={textContent:'Risks',focus(){context.document.activeElement=this;},isConnected:true};
const host={contains:n=>controls.includes(n),querySelectorAll:()=>controls,querySelector:()=>activeTab};
Object.assign(context,{host,document:{activeElement:null}});
const dashboard=read('assets/dashboard.js');
vm.runInContext(dashboard.slice(dashboard.indexOf('  function focusKey('),dashboard.indexOf('  const el =')),context);
const make=(text,key)=>({id:'',dataset:key?{focusKey:key}:{},tagName:'BUTTON',textContent:text,closest:()=>null,getAttribute:()=>null,isConnected:false,focus(){context.document.activeElement=this;}});
const old=make('Risks');controls.push(old);context.document.activeElement=old;
const saved=context.captureDashboardFocus();const replacement=make('Risks');controls.splice(0,1,replacement);context.restoreDashboardFocus(saved);assert.equal(context.document.activeElement,replacement);
const width=make('Expand Gantt','gantt:width');controls.splice(0,1,width);context.document.activeElement=width;
const widthFocus=context.captureDashboardFocus();const narrow=make('Use normal width','gantt:width');controls.splice(0,1,narrow);context.restoreDashboardFocus(widthFocus);assert.equal(context.document.activeElement,narrow);
const filter=make('','');filter.tagName='SELECT';filter.closest=()=>({querySelector:()=>({textContent:'Explore Agreement risks'})});controls.splice(0,1,filter);context.document.activeElement=filter;
const filterFocus=context.captureDashboardFocus();const newFilter={...filter,focus(){context.document.activeElement=this;}};controls.splice(0,1,newFilter);context.restoreDashboardFocus(filterFocus);assert.equal(context.document.activeElement,newFilter);
const missing=make('Removed action');controls.splice(0,1,missing);context.document.activeElement=missing;const removed=context.captureDashboardFocus();controls.length=0;context.restoreDashboardFocus(removed);assert.equal(context.document.activeElement,activeTab);
const external=make('Outside dashboard');context.document.activeElement=external;assert.equal(context.captureDashboardFocus(),null);
console.log('Dashboard focus: tabs, changing labels, filters, removed-control fallback and external focus PASS');
